const assert=require('node:assert/strict');
async function run(page,url='http://127.0.0.1:8766') {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(url,{waitUntil:'domcontentloaded'});
  await page.locator('.svg-key').first().waitFor();
  await page.locator('[data-tab="harmony"]').click();await page.locator('#btn-edit-harmony-toggle').click();
  await page.locator('#he-color-mode').selectOption('uniform');await page.locator('#he-color').fill('#c5bff8');
  await page.locator('[title="Transform"]').first().click();
  assert.equal(await page.locator('#tf-lock,#tf-theme,#tf-status,.tf-navigation').count(),0);
  assert.equal(await page.locator('#tf-stage-actions #tf-fit svg').count(),1);
  assert.equal(await page.locator('.tf-toolbar .logo > svg').evaluate(e=>e.getBoundingClientRect().width),24);
  await page.locator('#tf-tones').fill('1,3,5');
  const letters=page.locator('#tf-lettering input');
  assert.deepEqual(await letters.evaluateAll(es=>es.map(e=>e.value)),['a','b','c']);
  assert.deepEqual(await page.locator('#tf-lettering tbody tr td:first-child').allTextContents(),['1','3','5']);
  await page.getByLabel('Letter for 3',{exact:true}).fill('β');
  await page.getByLabel('Letter for 5',{exact:true}).fill('q');
  assert.equal(await page.locator('.tf-point[data-monomial="aβ"]').count(),1);
  await page.getByLabel('Letter for 5',{exact:true}).fill('a');
  assert.equal(await page.getByLabel('Letter for 5',{exact:true}).getAttribute('aria-invalid'),'true');
  await page.getByLabel('Letter for 5',{exact:true}).fill('q');
  await page.locator('#tf-save').click();
  await page.locator('[data-tf-tab="design"]').click();
  assert.equal(await page.locator('[data-setting="schritt.uniformColor"]').inputValue(),'#c5bff8');
  assert.equal(await page.locator('[data-setting="wechsel.uniformColor"]').inputValue(),'#f2f8bf');
  assert.equal(await page.locator('.tf-point[data-monomial="aq"] > [fill]').first().getAttribute('fill'),'#f2f8bf');
  assert.equal(await page.locator('.tf-point[data-monomial="aq"] > text').evaluate(e=>e.style.paintOrder),'stroke');
  await page.locator('[data-tf-tab="layout"]').click();
  assert.equal(await page.locator('[data-setting="toneLabels.hideDerived"]').isChecked(),false);
  const headers=async selector=>page.locator(`${selector} .tone-table th`).allTextContents();
  const point=label=>page.locator(`.tf-point[data-depth="0"][data-monomial="${label}"]`);
  await point('aq').click();
  assert.deepEqual(await headers('#tf-point-menu'),['','Tone','Name','Letter','¢','Hz']);
  assert.equal(await page.locator('.tf-hover-visible').count(),0);
  await page.locator('#tf-title').click();
  assert.equal(await page.locator('#tf-point-menu').isVisible(),false);
  assert.equal(await page.locator('.tf-selected,.tf-hover-visible').count(),0);
  await point('aq').click();await page.locator('#tf-point-menu [aria-label="Pin panel"]').click();
  assert.equal(await page.locator('.tf-pinned-panel').count(),1);
  await point('aβ').click();await page.locator('#tf-point-menu [aria-label="Pin panel"]').click();
  assert.equal(await page.locator('.tf-pinned-panel').count(),2);
  await page.locator('#tf-title').click();
  assert.equal(await page.locator('.tf-pinned-panel:visible').count(),2);
  await point('a^2').press('Enter');
  await page.locator('.tf-pinned-panel').first().locator('.tf-menu-title').click({position:{x:260,y:12}});
  assert.equal(await page.locator('#tf-point-menu').isVisible(),false);
  assert.equal(await page.locator('.tf-hover-visible').count(),0);
  const card=page.locator('.tf-pinned-panel').first(),bar=await card.locator('.tf-menu-title').boundingBox();
  const before=await card.boundingBox();
  await page.mouse.move(bar.x+35,bar.y+12);await page.mouse.down();
  await page.mouse.move(bar.x-165,bar.y+55,{steps:5});await page.mouse.up();
  const moved=await card.boundingBox();assert.ok(moved.x<before.x-50);
  assert.equal(await page.locator('.tf-hover-visible').count(),0);
  await page.locator('[data-setting="circle.edgeWidth"]').fill('7');
  assert.equal(await page.locator('.tf-pinned-panel:visible').count(),2);
  assert.ok(Math.abs((await card.boundingBox()).x-moved.x)<1);
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.locator('.tf-pinned-panel').count(),2);
  assert.equal(await page.locator('.tf-pinned-panel:visible').count(),0);
  await page.locator('#tf-collapse').click();
  await page.locator('.tf-pinned-panel').first().waitFor({state:'visible'});
  assert.equal(await page.locator('.tf-pinned-panel:visible').count(),2);
  await page.locator('#tf-show-panel').click();
  await page.setViewportSize({width:1440,height:960});
  // A positioned modal retains its manually constrained size after resize.
  const edge=await page.locator('.tf-resize-e').boundingBox();
  await page.mouse.move(edge.x+3,edge.y+50);await page.mouse.down();
  await page.mouse.move(edge.x+653,edge.y+50,{steps:6});await page.mouse.up();
  await page.locator('.tf-pinned-panel').first().waitFor({state:'visible'});
  assert.equal(await page.locator('.tf-pinned-panel:visible').count(),2);
  await card.locator('[aria-label="Unpin panel"]').click();
  assert.equal(await page.locator('.tf-pinned-panel').count(),1);
  assert.equal(await page.locator('#tf-point-menu').isVisible(),true);
  await page.locator('#tf-title').click();
  await page.locator('.tf-pinned-panel [aria-label="Close actions"]').click();
  assert.equal(await page.locator('.tf-pinned-panel').count(),0);
  await page.locator('[data-tf-tab="transformations"]').click();
  const row=()=>page.locator('#tf-pane-transformations .tf-list-item[data-monomial="aq"]');
  await row().hover();await page.locator('.tf-hover-visible circle').first().waitFor();
  await row().click();assert.equal(await row().evaluate(e=>e.classList.contains('selected')),true);
  assert.deepEqual(await headers('#tf-pane-transformations'),['','Tone','Name','Letter','¢','Hz']);
  assert.ok((await page.locator('#tf-pane-transformations .tf-tone-letter').allTextContents()).every(Boolean));
  await row().click();assert.equal(await page.locator('#tf-pane-transformations .tone-table').count(),0);
  await row().locator('[data-action="pin"]').click();
  await page.locator('[data-tf-tab="pinned"]').click();
  const pinned=page.locator('#tf-pane-pinned .tf-list-item');
  await pinned.click();assert.equal(await pinned.evaluate(e=>e.classList.contains('selected')),true);
  await pinned.click();assert.equal(await pinned.evaluate(e=>e.classList.contains('selected')),false);
  await page.locator('[data-tf-tab="transformations"]').click();
  await row().locator('[data-action="transport"]').click();
  assert.equal(await page.evaluate(()=>harmonies.find(h=>h.transport).uniformColor),'#f2f8bf');
  await page.locator('[data-tf-tab="transported"]').click();
  const transported=page.locator('#tf-pane-transported .tf-list-item');
  await transported.hover();await page.locator('.tf-hover-visible circle').first().waitFor();
  await transported.click();assert.deepEqual(await headers('#tf-pane-transported'),['','Tone','Name','Letter','¢','Hz']);
  await transported.click();assert.equal(await page.locator('#tf-pane-transported .tone-table').count(),0);
  await page.locator('#tf-save').click();
  const saved=JSON.parse(await page.evaluate(()=>buildProjectJSON()));
  saved.harmonies[0].transformer.viewLocked=true; // obsolete setting must not disable pan/zoom
  await page.locator('#tf-close').click();
  const keyboardHeaders=await page.locator('#harmony-editor .tone-table th').allTextContents();
  assert.ok(keyboardHeaders.includes('W'));assert.ok(!keyboardHeaders.includes('Letter'));
  await page.locator('#import-file').setInputFiles({name:'lettering.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
  await page.locator('[data-tab="harmony"]').click();await page.locator('[title="Transform"]').first().click();
  await page.locator('[data-tf-tab="harmony"]').click();
  assert.deepEqual(await page.locator('#tf-lettering input').evaluateAll(es=>es.map(e=>e.value)),['a','β','q']);
  await page.locator('#tf-collapse').click();
  const camera=await page.locator('#tf-diagram').getAttribute('viewBox'),box=await page.locator('#tf-diagram').boundingBox();
  await page.mouse.move(box.x+50,box.y+50);await page.mouse.wheel(0,-120);
  await page.waitForFunction(v=>document.querySelector('#tf-diagram').getAttribute('viewBox')!==v,camera);
  assert.deepEqual(errors,[]);
}
module.exports=run;
if(require.main===module)(async()=>{
  const {chromium}=require('playwright'),browser=await chromium.launch({headless:true,channel:'chromium'});
  try{await run(await browser.newPage({viewport:{width:1440,height:960}}),process.argv[2]);}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
