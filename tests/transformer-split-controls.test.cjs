const assert=require('node:assert/strict');
async function run(page,url='http://127.0.0.1:8766') {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(url,{waitUntil:'domcontentloaded'});await page.locator('.svg-key').first().waitFor();
  const box=s=>page.locator(s).boundingBox();
  let panel=await box('#side-panel'),top=await box('#top-bar-panel');
  assert.ok(Math.abs(panel.x-top.x)<1);assert.equal(await page.locator('#btn-toggle-config').isVisible(),false);
  const handle=await box('#panel-resize-handle');
  await page.mouse.move(handle.x+2,handle.y+100);await page.mouse.down();
  await page.mouse.move(handle.x-138,handle.y+100,{steps:6});await page.mouse.up();
  panel=await box('#side-panel');assert.ok(panel.width>450);
  await page.locator('#panel-toggle').click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('#keyboard-svg').getBoundingClientRect().width-innerWidth)<2);
  await page.waitForFunction(()=>Number(document.querySelector('#svg-axes > rect').getAttribute('width'))>=innerWidth-1);
  assert.ok(await page.locator('.svg-key').evaluateAll(es=>es.some(e=>e.getBoundingClientRect().x>1000&&e.getBoundingClientRect().x<1400)));
  assert.equal(await page.locator('#top-bar-panel').isVisible(),false);
  const gear=await box('#btn-toggle-config');assert.ok(gear.x+gear.width>1410);
  await page.locator('#btn-toggle-config').click();
  assert.ok(Math.abs((await box('#side-panel')).width-panel.width)<1);
  assert.ok(Math.abs((await box('#top-bar-panel')).x-(await box('#side-panel')).x)<1);
  await page.locator('[data-tab="harmony"]').click();await page.locator('#btn-edit-harmony-toggle').click();
  await page.locator('[title="Transform"]').first().click();
  assert.equal(await page.locator('#tf-reset-style').count(),0);
  assert.equal(await page.locator('.tf-toolbar .logo svg circle').count(),2);
  assert.ok(!(await page.locator('#tf-title').textContent()).includes('Transformer'));
  panel=await box('#tf-panel');top=await box('#tf-toolbar-panel');
  assert.ok(Math.abs(panel.x-top.x)<1);assert.ok(Math.abs(panel.width-top.width)<1);
  assert.ok((await box('#tf-save')).x>=panel.x);
  const before=await box('.tf-point[data-monomial="1"]');
  await page.locator('#tf-collapse').click();
  const after=await box('.tf-point[data-monomial="1"]');
  for(const k of ['x','y','width','height'])assert.ok(Math.abs(after[k]-before[k])<.05);
  assert.equal(await page.locator('#tf-save').isVisible(),false);
  assert.equal(await page.locator('#tf-close').isVisible(),true);
  assert.ok(Math.abs((await box('.tf-stage')).width-(await box('.tf-content')).width)<1);
  const theme=await page.locator('html').getAttribute('data-theme');
  await page.locator('#tf-theme').click();
  assert.notEqual(await page.locator('html').getAttribute('data-theme'),theme);
  await page.locator('#tf-theme').click();
  await page.locator('#tf-lock').click();
  const camera=await page.locator('#tf-diagram').getAttribute('viewBox');
  const canvas=await box('#tf-diagram');await page.mouse.move(canvas.x+100,canvas.y+100);await page.mouse.wheel(0,-120);
  assert.equal(await page.locator('#tf-diagram').getAttribute('viewBox'),camera);
  assert.equal(await page.locator('#tf-fit').isDisabled(),true);
  await page.locator('#tf-lock').click();
  await page.locator('#tf-show-panel').click();
  assert.equal(await page.locator('#tf-save').evaluate(e=>e.classList.contains('tf-dirty')),false);
  await page.locator('#tf-tones').fill('1, 5/4, 3/2');
  await page.locator('[data-tf-tab="layout"]').click();
  const labelSection=page.locator('[data-setting="toneLabels.show"]').locator('xpath=ancestor::details[1]');
  const order=await labelSection.locator('.tf-section-body [data-setting]').evaluateAll(es=>es.map(e=>e.dataset.setting));
  assert.deepEqual(order.slice(0,5),['toneLabels.type','toneLabels.fontSize','toneLabels.offset','toneLabels.showLetter','toneLabels.hideDerived']);
  assert.equal(await page.locator('[data-setting="toneLabels.offsetX"],[data-setting="toneLabels.offsetY"]').count(),0);
  await page.locator('[data-setting="toneLabels.type"]').selectOption('ratio');
  await page.locator('[data-setting="toneLabels.offset"]').fill('30');
  await page.locator('.tf-point[data-monomial="bc"]').click();
  await page.locator('#tf-point-menu [aria-label="Pin neighborhood"]').click();
  await page.locator('#tf-point-menu [aria-label="Close actions"]').click();
  for(const depth of [0,1]) {
    const data=await page.evaluate(depth=>{
      const circle=document.querySelector(`.tf-circle[data-depth="${depth}"][data-tone-index="0"]`);
      const label=document.querySelector(`.tf-tone-label[data-depth="${depth}"][data-tone-index="0"] text`);
      return [Number(circle.getAttribute('cx')),Number(circle.getAttribute('cy')),Number(label.getAttribute('x')),Number(label.getAttribute('y'))];
    },depth);
    assert.ok(Math.abs(Math.hypot(data[2]-data[0],data[3]-data[1])-30)<.01);
  }
  await page.locator('[data-setting="toneLabels.offset"]').fill('-15');
  const rootCircle=page.locator('.tf-circle[data-depth="0"][data-tone-index="0"]');
  const rootLabel=page.locator('.tf-tone-label[data-depth="0"][data-tone-index="0"] text');
  assert.ok(Number(await rootLabel.getAttribute('y'))>Number(await rootCircle.getAttribute('cy')));
  await page.locator('[data-tf-tab="harmony"]').click();await page.locator('#tf-tones').fill('1, 9/8, 3/2');
  await page.locator('[data-tf-tab="layout"]').click();
  const collapseSection=page.locator('[data-setting="showCollapses"]').locator('xpath=ancestor::details[1]');
  assert.deepEqual(await collapseSection.locator('.tf-section-body [data-setting]').evaluateAll(es=>es.map(e=>e.dataset.setting)),
    ['collapses.edgeWidth','collapses.edgeColor','collapses.hideWeak','collapses.hideDerived']);
  await page.locator('[data-setting="showCollapses"]').check();
  assert.ok(await page.locator('[data-kind="sw"]').count()>0);
  await page.locator('[data-setting="collapses.hideWeak"]').check();
  assert.equal(await page.locator('[data-kind="sw"]').count(),0);
  assert.ok(await page.locator('[data-kind="ww"]').count()>0);assert.ok(await page.locator('[data-kind="ss"]').count()>0);
  await page.locator('[data-setting="collapses.hideWeak"]').uncheck();
  assert.ok(await page.locator('[data-kind="sw"]').count()>0);
  await page.locator('.tf-point[data-monomial="1"][data-depth="0"]').click();
  assert.equal(await page.locator('#tf-point-menu .tf-menu-action').count(),0);
  assert.equal(await page.locator('#tf-point-menu .tone-table tbody tr').count(),3);
  await page.locator('#tf-point-menu [aria-label="Close actions"]').click();
  await page.locator('[data-tf-tab="transformations"]').click();
  assert.equal(await page.locator('#tf-collection-title').count(),0);
  const row=page.locator('#tf-pane-transformations .tf-list-item[data-monomial="a/b"]');
  await row.click();
  assert.equal(await row.locator('..').locator('.tf-selected-tones .tone-table tbody tr').count(),3);
  const activeWidth=(await box('[data-tf-tab="transformations"]')).width;
  assert.ok(activeWidth<180);
  await page.locator('#tf-save').click();
  await row.locator('[data-action="transport"]').click();
  await page.locator('[data-tf-tab="transported"]').click();
  await page.locator('#tf-pane-transported .tf-list-item').click();
  assert.equal(await page.locator('#tf-pane-transported .tf-selected-tones .tone-table tbody tr').count(),3);
  await page.locator('[data-tf-tab="transformations"]').click();
  await page.locator('#tf-pane-transformations .tf-list-item[data-monomial="bc"] [data-action="pin"]').click();
  await page.locator('[data-tf-tab="pinned"]').click();await page.locator('#tf-pane-pinned .tf-list-item').click();
  assert.equal(await page.locator('#tf-pane-pinned .tone-table,#tf-pane-pinned .tf-pinned-transformations').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS matching split toolbars/canvases, radial labels, weak-collapse filtering, identity and simplified collections');
}
module.exports=run;
if(require.main===module) {
  (async()=>{const {chromium}=require('playwright');const browser=await chromium.launch({headless:true,channel:'chromium'});
    try{await run(await browser.newPage({viewport:{width:1440,height:960}}),process.argv[2]);}finally{await browser.close();}
  })().catch(e=>{console.error(e);process.exitCode=1;});
}
